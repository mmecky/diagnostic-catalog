create table component
(
    id   bigint generated by default as identity primary key,
    name text unique not null
);

create table entry
(
    id           bigint generated by default as identity primary key,
    symptom      text                             not null,
    cause        text                             not null,
    remedy       text                             not null,
    component_id bigint references component (id) not null
);

create table entry_tags
(
    entry_id bigint references entry (id) not null,
    tags     text                         not null,
    primary key (entry_id, tags)
);
